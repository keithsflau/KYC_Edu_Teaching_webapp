const WORD = Object.keys(MAP).filter((k) => k.length > 1).sort((a, b) => b.length - a.length);
const CHAR = {};
for (const [k, v] of Object.entries(MAP)) if (k.length === 1) CHAR[k] = v;

function convert(text) {
  for (const w of WORD) text = text.split(w).join(MAP[w]);
  return text.replace(/[\u4e00-\u9fff]/g, (ch) => CHAR[ch] || ch);
}

const ROOT = path.join(__dirname, "..");
const files = [
  path.join(__dirname, "battle-enrichment-cse.js"),
  path.join(__dirname, "battle-leaders-cse.js"),
  path.join(__dirname, "battles-catalog-cse.js"),
];
function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".js") || name.endsWith(".html")) files.push(p);
  }
}
walk(path.join(ROOT, "wars"));

let changed = 0;
for (const file of files) {
  if (file.includes("three.min") || file.includes("OrbitControls") || file.includes("CSS2DRenderer")) continue;
  const raw = fs.readFileSync(file, "utf8");
  const next = convert(raw);
  if (next !== raw) {
    fs.writeFileSync(file, next);
    changed++;
  }
}
console.log("converted", changed, "files");
